import path from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { compileTikz } from '../src/diagrams.js';

try {
  if (!process.argv[2]) throw new Error('Usage: npm run diagram -- /path/to/figure.tikz [more.tikz]');
  for (const filename of process.argv.slice(2)) {
    if (path.extname(filename) !== '.tikz') throw new Error('Expected a .tikz drawing source.');
    const output = filename.slice(0,-5) + '.svg';
    const previous = await readFile(output,'utf8').catch(error => { if (error.code !== 'ENOENT') throw error; return ''; });
    if (previous && !previous.includes('data-ridge-diagram="tikz-v1"')) throw new Error(`Refusing to replace an SVG not generated by this tool: ${output}`);
    const svg = await compileTikz(await readFile(filename,'utf8'));
    await writeFile(output,svg + '\n');
    console.log(output);
  }
} catch (error) { console.error(error.message); process.exitCode = 1; }
